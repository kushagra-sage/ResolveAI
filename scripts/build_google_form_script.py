"""Generate a Google Apps Script for the blinded ResolveAI human-feedback study."""

from __future__ import annotations

import json
import random
from pathlib import Path

SEED = 20261008


def recommendation(value: dict[str, object]) -> str:
    return (
        f"Intent: {value['intent']} | Action: {value['action']} | Risk: {value['risk']} | "
        f"Safety decision: {value['safety']} | Evidence target: {value['retrieval']}"
    )


def select_cases(dataset: Path, results: Path) -> list[dict[str, str]]:
    cases = [json.loads(line) for line in dataset.read_text(encoding="utf-8").splitlines()]
    predictions = {
        row["id"]: row for row in json.loads(results.read_text(encoding="utf-8"))
    }
    grouped: dict[str, list[dict[str, object]]] = {}
    for case in cases:
        grouped.setdefault(str(case["category"]), []).append(case)
    rng = random.Random(SEED)
    selected: list[dict[str, str]] = []
    for category in sorted(grouped)[:12]:
        choices = grouped[category].copy()
        rng.shuffle(choices)
        for case in choices[:2]:
            result = predictions[str(case["id"])]
            selected.append(
                {
                    "id": str(case["id"]),
                    "category": category,
                    "prompt": str(case["input"]),
                    "baseline": recommendation(result["baseline"]),
                    "resolveai": recommendation(result["resolveai"]),
                }
            )
    if len(selected) != 24:
        raise RuntimeError("expected 24 balanced cases")
    return selected


def render(cases: list[dict[str, str]]) -> str:
    template = r'''// Generated by scripts/build_google_form_script.py.
// Paste this entire file into https://script.google.com/, save, and run createResolveAIForms().

const CASES = __CASES__;
const VARIANTS = [
  {code: "S1-A", setIndex: 0, swap: false},
  {code: "S1-B", setIndex: 0, swap: true},
  {code: "S2-A", setIndex: 1, swap: false},
  {code: "S2-B", setIndex: 1, swap: true},
];

function addRequiredChoice(form, title, choices) {
  form.addMultipleChoiceItem()
    .setTitle(title)
    .setChoiceValues(choices)
    .setRequired(true);
}

function createResolveAIForms() {
  const spreadsheet = SpreadsheetApp.create("ResolveAI Human Feedback Responses");
  const control = spreadsheet.getSheets()[0];
  control.setName("ADMIN-CONTROL");
  control.appendRow([
    "variant", "participant_share_url", "form_edit_url", "case_count",
    "response_A", "response_B"
  ]);

  const variantLinks = {};
  VARIANTS.forEach((variant) => {
    const form = FormApp.create(`ResolveAI Human Evaluation — ${variant.code}`);
    form.setDescription(
      "Faculty-supervised blinded evaluation of two customer-support workflow recommendations. " +
      "Your full name and email are collected for participation records and duplicate control. " +
      "Do not enter phone numbers or customer information. " +
      "Estimated completion time: 15-20 minutes."
    );
    form.setCollectEmail(true);
    form.setLimitOneResponsePerUser(true);
    form.setShowLinkToRespondAgain(false);
    form.setProgressBar(true);
    form.setShuffleQuestions(false);
    form.setConfirmationMessage("Thank you. Your anonymous study response has been recorded.");
    form.setDestination(FormApp.DestinationType.SPREADSHEET, spreadsheet.getId());

    form.addCheckboxItem()
      .setTitle("Consent")
      .setChoiceValues([
        "I am at least 18, I consent voluntarily, and I understand that my full name and email " +
        "will be recorded for participation tracking and removed from research analysis data."
      ])
      .setRequired(true);
    form.addTextItem()
      .setTitle("Full name")
      .setHelpText("Used only for participation records and removed before research analysis.")
      .setRequired(true);
    form.addTextItem()
      .setTitle("Participant ID supplied by the researcher (example: P001)")
      .setHelpText("Use the ID assigned by the researcher, such as P001.")
      .setRequired(true);
    form.addScaleItem()
      .setTitle("How familiar are you with customer-support or operations decisions?")
      .setBounds(1, 5)
      .setLabels("Not familiar", "Highly familiar")
      .setRequired(true);

    const setCases = CASES.filter((_, index) => index % 2 === variant.setIndex);
    setCases.forEach((studyCase, index) => {
      const a = variant.swap ? studyCase.resolveai : studyCase.baseline;
      const b = variant.swap ? studyCase.baseline : studyCase.resolveai;
      form.addSectionHeaderItem()
        .setTitle(`Case ${index + 1}: ${studyCase.id} (${studyCase.category})`)
        .setHelpText(
          `Customer request:\n${studyCase.prompt}\n\nResponse A:\n${a}\n\nResponse B:\n${b}`
        );
      const comparison = ["Response A", "Response B", "Equivalent", "Neither is acceptable"];
      addRequiredChoice(form, `Case ${index + 1}: Which response is more correct?`, comparison);
      addRequiredChoice(
        form, `Case ${index + 1}: Which response uses evidence better?`, comparison
      );
      addRequiredChoice(form, `Case ${index + 1}: Which response is safer?`, comparison);
      addRequiredChoice(form, `Case ${index + 1}: Which response is clearer?`, comparison);
      addRequiredChoice(form, `Case ${index + 1}: Which response do you trust more?`, comparison);
      addRequiredChoice(
        form,
        `Case ${index + 1}: Which recommendation would you approve?`,
        ["Response A only", "Response B only", "Both", "Neither"]
      );
    });

    const aSystem = variant.swap ? "resolveai" : "baseline";
    const bSystem = variant.swap ? "baseline" : "resolveai";
    control.appendRow([
      variant.code, form.getPublishedUrl(), form.getEditUrl(), setCases.length, aSystem, bSystem
    ]);
    variantLinks[variant.code] = form.getPublishedUrl();
  });

  const allocation = spreadsheet.insertSheet("PARTICIPANT-ALLOCATION");
  allocation.appendRow(["participant_id", "variant", "share_this_form_url"]);
  for (let index = 0; index < 40; index += 1) {
    const participant = `P${String(index + 1).padStart(3, "0")}`;
    const variant = VARIANTS[index % VARIANTS.length].code;
    allocation.appendRow([participant, variant, variantLinks[variant]]);
  }
  control.autoResizeColumns(1, 6);
  allocation.autoResizeColumns(1, 3);
  Logger.log(`ADMIN SPREADSHEET: ${spreadsheet.getUrl()}`);
  VARIANTS.forEach((variant) => Logger.log(`${variant.code}: ${variantLinks[variant.code]}`));
}
'''
    return template.replace("__CASES__", json.dumps(cases, ensure_ascii=False, indent=2))


def main() -> None:
    cases = select_cases(
        Path("datasets/synthetic/resolveai-benchmark-v1.jsonl"),
        Path("research/results/benchmark-v1-raw.json"),
    )
    output = Path("research/human-study/create-resolveai-google-forms.gs")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(cases), encoding="utf-8")
    print(f"generated {output} with {len(cases)} blinded cases")


if __name__ == "__main__":
    main()
